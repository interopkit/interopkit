/**
 * The requirements of cmi5 that CATAPULT lists (`requirements/requirements.json` of `@cmi5/requirements`), and how
 * `@interopkit/course-launch` meets each: one row for each requirement of the specification, with every id that CATAPULT gives
 * it, `(d)` marking one that CATAPULT derives for the LMS. A row without ids is a requirement that CATAPULT does not number.
 * `test/requirements.spec.test.ts` fails when an id of the pinned list has no row, has two, or a row names an id the list does
 * not have, and when a row names a test file that does not exist.
 *
 * @see {@link https://github.com/adlnet/CATAPULT/blob/main/requirements/requirements.json | CATAPULT, requirements.json}
 */

/** How the package meets a requirement. */
type RequirementState =
  /** Met, and proven by the tests named, files of `packages/course-launch/test/`. */
  | { readonly state: "has"; readonly tests: readonly string[] }
  /** Met as far as a library can, with what is left to the host and why. */
  | { readonly state: "in-part"; readonly tests: readonly string[]; readonly reason: string }
  /** Not met, with the reason. */
  | { readonly state: "excluded"; readonly reason: string };

/** A requirement of cmi5: its section, the ids CATAPULT gives it, what it asks, who it binds, and how it is met. */
export interface Cmi5Requirement {
  readonly section: string;
  readonly ids: readonly string[];
  readonly asks: string;
  readonly roles: "LMS" | "AU" | "LMS, publisher" | "Both" | "Neither";
  readonly met: RequirementState;
}

